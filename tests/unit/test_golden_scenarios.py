def test_net_metering_ledger_matches_fixture(fixture_data):
    case = fixture_data["standalone_cases"]["net_metering_ledger_two_months"]
    ledger = NetMeteringLedger(export_credit_rate_cad_per_kwh=case["inputs"]["export_credit_rate_cad_per_kwh"])
