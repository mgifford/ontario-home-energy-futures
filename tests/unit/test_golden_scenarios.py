"""Python side of the cross-language golden-file drift guard.

tests/fixtures/golden_scenarios.json was generated by actually running
model/scenario.py and friends (see scripts/generate_golden_scenarios.py) -
this test re-runs the same functions and confirms Python's output still
matches the recorded fixture (a standard snapshot/regression test).

The JS side (tests/js/test_golden_scenarios.mjs) checks the SAME fixture
against the ported JavaScript implementation in web/static/calculator.js -
that is the test that actually catches Python/JS drift. This Python test
mostly guards against an accidental Python regression changing behaviour
without the fixture being regenerated deliberately.

If a change to model/scenario.py is intentional, regenerate the fixture:
    python3 scripts/generate_golden_scenarios.py
and update web/static/calculator.js to match before committing.
"""

