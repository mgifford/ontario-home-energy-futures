@pytest.fixture(scope="module")
def fixture_data():
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def _run_scenario_case(case: dict):
    inputs = dict(case["inputs"])
    if case["function"] == "evaluate_grid_only":
        inputs["price_scenario"] = PRICE_SCENARIOS[inputs["price_scenario"]]
        return evaluate_grid_only(**inputs)
    elif case["function"] == "evaluate_solar_purchase":
        inputs["price_scenario"] = PRICE_SCENARIOS[inputs["price_scenario"]]
        inputs["decline_scenario"] = DECLINE_SCENARIOS[inputs["decline_scenario"]]
        inputs["base_quote"] = QuoteComponents(**inputs["base_quote"])
        return evaluate_solar_purchase(**inputs)
    raise ValueError(f"unknown function {case['function']!r}")


def test_fixture_file_exists_and_has_cases(fixture_data):
    assert len(fixture_data["scenario_cases"]) >= 5
    assert len(fixture_data["standalone_cases"]) >= 5


@pytest.mark.parametrize("case_index", range(7))
def test_scenario_case_matches_fixture(fixture_data, case_index):
    case = fixture_data["scenario_cases"][case_index]
    result = _run_scenario_case(case)
    expected = case["expected"]

    assert result.label == expected["label"]
    assert result.purchase_year_offset == expected["purchase_year_offset"]
    assert result.initial_cost_cad == pytest.approx(expected["initial_cost_cad"], abs=0.01)
    assert result.financing_interest_cad == pytest.approx(expected["financing_interest_cad"], abs=0.01)
    assert result.group_discount_cad == pytest.approx(expected["group_discount_cad"], abs=0.01)
    assert result.total_nominal_cad == pytest.approx(expected["total_nominal_cad"], abs=0.01)
    assert result.total_present_value_cad == pytest.approx(expected["total_present_value_cad"], abs=0.01)
    assert result.simple_payback_years == expected["simple_payback_years"]

    assert len(result.annual_cash_flows) == len(expected["annual_cash_flows"])
    for actual_flow, expected_flow in zip(result.annual_cash_flows, expected["annual_cash_flows"]):
        assert actual_flow.year == expected_flow["year"]
        assert actual_flow.total_nominal_cad == pytest.approx(expected_flow["total_nominal_cad"], abs=0.01)
        assert actual_flow.total_present_value_cad == pytest.approx(expected_flow["total_present_value_cad"], abs=0.01)


